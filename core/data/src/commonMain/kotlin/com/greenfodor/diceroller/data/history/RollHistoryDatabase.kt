package com.greenfodor.diceroller.data.history

import androidx.room.ConstructedBy
import androidx.room.Database
import androidx.room.RoomDatabase
import androidx.room.RoomDatabaseConstructor
import androidx.room.TypeConverters
import androidx.sqlite.driver.bundled.BundledSQLiteDriver
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.IO

@Database(entities = [RollRecordEntity::class], version = 1, exportSchema = true)
@TypeConverters(IntListConverter::class)
@ConstructedBy(RollHistoryDatabaseConstructor::class)
abstract class RollHistoryDatabase : RoomDatabase() {
    abstract fun rollHistoryDao(): RollHistoryDao
}

/** Instantiates [RollHistoryDatabase]; the actual implementations are generated by Room. */
@Suppress("KotlinNoActualForExpect")
expect object RollHistoryDatabaseConstructor : RoomDatabaseConstructor<RollHistoryDatabase> {
    override fun initialize(): RollHistoryDatabase
}

/** File name of the roll history database. */
const val ROLL_HISTORY_DATABASE_NAME = "roll_history.db"

/** Builds the database from a platform [builder] with the bundled SQLite driver and IO queries. */
fun buildRollHistoryDatabase(builder: RoomDatabase.Builder<RollHistoryDatabase>): RollHistoryDatabase =
    builder
        .setDriver(BundledSQLiteDriver())
        .setQueryCoroutineContext(Dispatchers.IO)
        .build()
